const STRINGS: Record<UiLanguage, Record<UiKey, string>> = { en, sl };

type Values = Record<string, string | number>;

function fill(text: string, values: Values, language: UiLanguage): string {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    if (value === undefined) return match;
    return typeof value === "number" ? formatNumber(language, value) : value;
  });
}

export function translate(language: UiLanguage, key: UiKey, values: Values = {}): string {
  return fill(STRINGS[language][key], values, language);
}

