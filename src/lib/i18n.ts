export type PluralKey = keyof typeof PLURALS;

export function pluralize(language: UiLanguage, key: PluralKey, count: number): string {
  const n = Math.abs(Math.trunc(count));
  let form: string;
  if (language === "sl") {
    const lastTwo = n % 100;
    const forms = PLURALS[key].sl;
    form = lastTwo === 1 ? forms[0] : lastTwo === 2 ? forms[1] : lastTwo === 3 || lastTwo === 4 ? forms[2] : forms[3];
  } else {
    form = PLURALS[key].en[n === 1 ? 0 : 1];
  }
  return fill(form, { n: count }, language);
}

export function dateLocale(language: UiLanguage): string {
  return language === "sl" ? "sl-SI" : "en-GB";
}

/** 1,240 in English, 1.240 in Slovenian. */
export function formatNumber(language: UiLanguage, value: number): string {
  return value.toLocaleString(language === "sl" ? "sl-SI" : "en");
}

/** "just now", "5 min ago", "yesterday", "3 d ago". */
export function relativeTime(language: UiLanguage, iso: string, now = Date.now()): string {
  const minutes = Math.max(0, Math.round((now - new Date(iso).getTime()) / 60000));
  if (Number.isNaN(minutes)) return "";
  if (minutes < 1) return translate(language, "justNow");
  if (minutes < 60) return translate(language, "minutesAgo", { n: minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 24) return translate(language, "hoursAgo", { n: hours });
  const days = Math.round(hours / 24);
  if (days === 1) return translate(language, "yesterday");
  return pluralize(language, "daysAgo", days);
}

/** A book still called "Untitled" in either language, so an import may give it a name. */
export function isUntitled(title: string): boolean {
  return title === en.untitled || title === sl.untitled;
}

