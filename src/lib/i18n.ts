const STRINGS: Record<UiLanguage, Record<UiKey, string>> = { en, sl };

type Values = Record<string, string | number>;

function fill(text: string, values: Values, language: UiLanguage): string {
  return text.replace(/\{(\w+)\}/g, (match, name: string) => {
    const value = values[name];
    if (value === undefined) return match;
    return typeof value === "number" ? formatNumber(language, value) : value;
  });
}

export function translate(language: UiLanguage, key: UiKey, values: Values = {}): string {
  return fill(STRINGS[language][key], values, language);
}

/**
 * Counted phrases. English has two forms (1 word, 2 words); Slovenian has four, chosen by the last
 * two digits: 1 beseda, 2 besedi, 3 or 4 besede, and besed for everything else.
 */
const PLURALS = {
  words: { en: ["{n} word", "{n} words"], sl: ["{n} beseda", "{n} besedi", "{n} besede", "{n} besed"] },
  chapters: { en: ["{n} chapter", "{n} chapters"], sl: ["{n} poglavje", "{n} poglavji", "{n} poglavja", "{n} poglavij"] },
  daysAgo: { en: ["{n} d ago", "{n} d ago"], sl: ["pred {n} dnem", "pred {n} dnevoma", "pred {n} dnevi", "pred {n} dnevi"] },
  /** Follows the number of finished stories: "6 of 12 stories". */
  storiesOf: { en: ["of {n} story", "of {n} stories"], sl: ["od {n} zgodbe", "od {n} zgodb", "od {n} zgodb", "od {n} zgodb"] },
  openCount: { en: ["{n} open", "{n} open"], sl: ["{n} odprto", "{n} odprti", "{n} odprta", "{n} odprtih"] },
} satisfies Record<string, { en: [string, string]; sl: [string, string, string, string] }>;

export type PluralKey = keyof typeof PLURALS;

export function pluralize(language: UiLanguage, key: PluralKey, count: number): string {
  const n = Math.abs(Math.trunc(count));
  let form: string;
  if (language === "sl") {
    const lastTwo = n % 100;
    const forms = PLURALS[key].sl;
    form = lastTwo === 1 ? forms[0] : lastTwo === 2 ? forms[1] : lastTwo === 3 || lastTwo === 4 ? forms[2] : forms[3];
  } else {
    form = PLURALS[key].en[n === 1 ? 0 : 1];
  }
  return fill(form, { n: count }, language);
}

export function dateLocale(language: UiLanguage): string {
  return language === "sl" ? "sl-SI" : "en-GB";
}

/** 1,240 in English, 1.240 in Slovenian. */
export function formatNumber(language: UiLanguage, value: number): string {
  return value.toLocaleString(language === "sl" ? "sl-SI" : "en");
}

/** "just now", "5 min ago", "yesterday", "3 d ago". */
export function relativeTime(language: UiLanguage, iso: string, now = Date.now()): string {
  const minutes = Math.max(0, Math.round((now - new Date(iso).getTime()) / 60000));
  if (Number.isNaN(minutes)) return "";
  if (minutes < 1) return translate(language, "justNow");
  if (minutes < 60) return translate(language, "minutesAgo", { n: minutes });
  const hours = Math.round(minutes / 60);
  if (hours < 24) return translate(language, "hoursAgo", { n: hours });
  const days = Math.round(hours / 24);
  if (days === 1) return translate(language, "yesterday");
  return pluralize(language, "daysAgo", days);
}

/** A book still called "Untitled" in either language, so an import may give it a name. */
export function isUntitled(title: string): boolean {
  return title === en.untitled || title === sl.untitled;
}

// The Windows side reports problems in English; these are the ones a writer can run into.
const RUST_ERRORS = new Map<string, UiKey>(
  (
    [
      "errFolderForBackup",
      "errBackupExists",
      "errChooseBackupFile",
      "errBackupName",
      "errPathInvalid",
      "errContentsMissing",
      "errExportKinds",
      "errExampleName",
      "errProjectNotFound",
      "errFolderMissing",
      "errFolderHasDb",
      "errFolderHasBook",
      "errImageKinds",
      "errOneWord",
      "errNoSpellChecker",
      "errCannotRemoveWord",
    ] as const
  ).map((key) => [en[key], key]),
);
const OPEN_ELSEWHERE = /^“(.+)” is open in another program, probably Word\. Close it there, then try again\.$/;

/** Shows a problem reported in English by the Windows side in the interface language. */
export function localizeError(language: UiLanguage, message: string): string {
  const key = RUST_ERRORS.get(message);
  if (key) return translate(language, key);
  const open = OPEN_ELSEWHERE.exec(message);
  if (open) return translate(language, "errOpenElsewhere", { name: open[1] });
  return message;
}
